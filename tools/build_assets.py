"""Pack the PNG assets into badge-ready Lua. Run with Python and Pillow."""

import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SPRITES = ROOT / 'sprites'
OUT = ROOT / 'apps' / 'dust-range' / 'art'
SYMBOL_START = 35


def rectangles(image, skip):
    """Merge matching color runs across adjacent rows."""
    pixels = image.load()
    active = {}
    for y in range(image.height):
        runs = {}
        x = 0
        while x < image.width:
            color = pixels[x, y]
            end = x + 1
            while end < image.width and pixels[end, y] == color:
                end += 1
            if color[3] and color != skip:
                key = x, end - x, color[:3]
                runs[key] = active.pop(key, y)
            x = end
        for (x, width, color), top in active.items():
            yield x, top, width, y - top, color
        active = runs
    for (x, width, color), top in active.items():
        yield x, top, width, image.height - top, color


def pack(image, palette, skip=None):
    stream = []
    for x, y, width, height, color in rectangles(image, skip):
        index = palette.setdefault(color, len(palette) + 1)
        stream.extend(chr(value + SYMBOL_START) for value in (x, y, width, height, index))
    data = ''.join(stream)
    assert ']=]' not in data and all(35 <= ord(char) < 127 for char in data)
    return '[=[' + data + ']=]'


def cells(image, width, height, columns, rows):
    assert image.size == (width * columns, height * rows)
    assert set(image.getchannel('A').get_flattened_data()) <= {0, 255}
    return [[image.crop((x * width, y * height, (x + 1) * width, (y + 1) * height))
             for x in range(columns)] for y in range(rows)]


def read_png(path):
    with Image.open(path) as image:
        return image.convert('RGBA')


def write_module(name, lines):
    text = '-- Generated by tools/build_assets.py. Edit the PNG sources.\n' + '\n'.join(lines) + '\n'
    assert len(text.encode('ascii')) <= 256 * 1024
    (OUT / f'{name}.lua').write_text(text, encoding='ascii', newline='\n')


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    palette = {}
    hero_dir = SPRITES / 'hero'
    layout = json.loads((hero_dir / 'walk-layout.json').read_text())
    names = ['unarmed', 'handgun', 'assault-rifle', 'pump-shotgun', 'grenade',
             'rocket-launcher', 'flamethrower', 'tnt', 'rail-rifle', 'bankshot',
             'boomerang-disc', 'arc-projector', 'cryo-sprayer', 'charge-cannon',
             'gravity-orb', 'shock-hammer']
    width, height = layout['frameWidth'], layout['frameHeight']
    directions = len(layout['directionRowsTopToBottom'])
    columns = layout['framesPerDirection']
    idle = cells(read_png(hero_dir / layout['idleSheet']['image']), width, height, len(names), directions)
    idle_order = layout['idleSheet']['columnsLeftToRight']
    for name in names:
        sheet = read_png(hero_dir / layout['sheets'][name])
        walk = cells(sheet, width, height, columns, directions)
        lines = ['return {']
        for row, poses in enumerate(walk):
            images = [idle[row][idle_order.index(name)], *poses]
            lines.append('  {' + ','.join(pack(image, palette) for image in images) + '},')
        lines.append('}')
        write_module(name, lines)

    icons = ['return {']
    for name in names[1:]:
        image = read_png(SPRITES / 'weapons' / f'{name}.png')
        icons.append(f'  {{{image.width},{image.height},{pack(image, palette)}}},')
    write_module('icons', [*icons, '}'])

    effects_dir = SPRITES / 'effects'
    layout = json.loads((effects_dir / 'effects-layout.json').read_text())
    by_weapon = {}
    for entry in layout['effects']:
        by_weapon.setdefault(entry['weapon'], []).append(entry)
    for weapon, entries in by_weapon.items():
        lines = ['-- Rows are facings N..NW for directional effects. Pivot is the frame centre.',
                 'return {']
        for entry in entries:
            sheet = read_png(effects_dir / entry['image'])
            rows = cells(sheet, entry['frameWidth'], entry['frameHeight'], entry['frames'], entry['rows'])
            lines.append(f"  ['{entry['name']}'] = {{w={entry['frameWidth']},h={entry['frameHeight']},"
                         f"fps={entry['framesPerSecond']},directional={str(entry['directional']).lower()},")
            for row in rows:
                lines.append('    {' + ','.join(pack(image, palette) for image in row) + '},')
            lines.append('  },')
        lines.append('}')
        write_module(f'fx-{weapon}', lines)

    terrain = SPRITES / 'terrain'
    layout = json.loads((terrain / 'terrain-layout.json').read_text())
    size = layout['tileWidth']
    assert size == layout['tileHeight'] == 16
    tiles = cells(read_png(terrain / layout['image']), size, size, layout['columns'], layout['rows'])
    ground = tiles[0][0].getpixel((0, 0))
    lines = ['return {']
    for row in tiles:
        for tile in row:
            images = [tile] + [tile.transpose(rotate) for rotate in (
                Image.Transpose.ROTATE_90, Image.Transpose.ROTATE_180, Image.Transpose.ROTATE_270)]
            lines.extend('  ' + pack(image, palette, skip=ground) + ',' for image in images)
    write_module('terrain', [*lines, '}'])
    assert len(palette) + SYMBOL_START < 127, f'{len(palette)} colours overflow the packed index'
    colors = ','.join('0x%02x%02x%02x' % color for color in palette)
    write_module('palette', ['return {', f'  ground = 0x%02x%02x%02x,' % ground[:3], f'  colors = {{{colors}}},', '}'])
    level_tiles()


def lua_value(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, dict):
        return '{' + ','.join(f'{k}={lua_value(v)}' for k, v in value.items()) + '}'
    if isinstance(value, list):
        return '{' + ','.join(lua_value(v) for v in value) + '}'
    raise TypeError(value)


LEVEL_FIELDS = ('walk', 'shots', 'lobs', 'sight', 'pierce', 'hp', 'breaksTo', 'explodes',
                'slow', 'hazard', 'overhead', 'autotile', 'group', 'terrain', 'layer', 'span', 'bounds',
                'height', 'underlay', 'variants')


def level_tiles():
    """Pack the level tileset and its gameplay properties. Tiles keep their own palette."""
    tiles = SPRITES / 'tiles'
    spec = json.loads((tiles / 'materials.json').read_text())
    layout = json.loads((tiles / 'tiles-layout.json').read_text())
    size, columns = layout['tileSize'], layout['columns']
    sheet = read_png(tiles / layout['image'])
    palette = {}
    lines = ['-- Level tiles. Properties come from sprites/tiles/materials.json.',
             '-- art[id][variant] is packed like the other sprites, with indexes into colors.',
             '-- opaque[id] has one character per variant: 1 = no transparent pixels.',
             'return {', '  materials = {']
    art, opaque = [], []
    for material in spec['materials']:
        mid = material['id']
        fields = {k: material[k] for k in LEVEL_FIELDS if k in material}
        lines.append(f'    [{json.dumps(mid)}] = {lua_value(fields)},')
        entry = layout['materials'].get(mid)
        if not entry:
            continue
        packed, flags = [], ''
        for index in range(entry['variants']):
            row = entry['row'] + index // columns
            col = index % columns
            image = sheet.crop((col * size, row * size, (col + 1) * size, (row + 1) * size))
            alpha = set(image.getchannel('A').get_flattened_data())
            assert alpha <= {0, 255}, f'{mid} has semi-transparent pixels'
            packed.append(pack(image, palette))
            flags += '1' if alpha == {255} else '0'
        art.append(f'    [{json.dumps(mid)}] = {{{",".join(packed)}}},')
        opaque.append(f'    [{json.dumps(mid)}] = "{flags}",')
    assert len(palette) + SYMBOL_START < 127, f'{len(palette)} tile colours overflow the packed index'
    colors = ','.join('0x%02x%02x%02x' % color[:3] for color in palette)
    lines += ['  },', f'  colors = {{{colors}}},', '  art = {', *art, '  },', '  opaque = {', *opaque, '  },', '}']
    write_module('tiles', lines)


if __name__ == '__main__':
    main()
